/* Pořadí dlaždic v editoru – jako v originále: půlky cihel, cihla, půlky oceli, ocel, voda, les, led, nic. */
T.EDITOR_TYPY = ['>', 'v', '<', '^', '#', ')', '_', '(', '=', '@', '~', '%', ':', '.'];

const ZRCADLO = { '>': '<', '<': '>', ')': '(', '(': ')' };
/* 13 plných řádků (souměrné poloviny doplní zrcadlením). */
T.rozbalMapu = function (radky) {
  return radky.map(r => r.length === 13 ? r
    : r + r.slice(0, 6).split('').reverse().map(c => ZRCADLO[c] || c).join(''));
};

/* Dlaždice, které musí zůstat prázdné: zrod nepřátel, zrod hráčů, orel a jeho hradba. */
T.CHRANENE = [[0, 0], [6, 0], [12, 0], [4, 12], [8, 12], [5, 11], [6, 11], [7, 11], [5, 12], [6, 12], [7, 12]];
T.vycistiMapu = function (radky) {
  const m = T.rozbalMapu(radky).map(r => r.split(''));
  for (const [x, y] of T.CHRANENE) m[y][x] = '.';
  return m.map(r => r.join(''));
};

